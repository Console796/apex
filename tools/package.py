#!/usr/bin/env python3
"""Apex release packaging (plan 0.1.10; .deb, .rpm and the Windows installer since 0.6.8-release).

    tools/package.py [--build-dir DIR] [--out DIR] [--formats LIST] [--no-bundle-qt] [--qt-prefix DIR]
    tools/package.py --installer ZIP [--out DIR]

Takes an existing build tree (default build/linux-gcc-release, or build/windows-msvc-release on
Windows) of the `apex` target, runs `cmake --install --strip` into a staging directory, and writes
the packages into --out (default dist/). On Linux, --formats picks from txz, deb and rpm (default
all three):

  apex-<version>-linux-x86_64.tar.xz  bundles Qt
      apex-<version>/apex             launcher script (sets LD_LIBRARY_PATH, QT_PLUGIN_PATH)
      apex-<version>/bin/apex         the executable
      apex-<version>/lib/             Qt libraries (ldd closure minus glibc/GPU/system libs)
      apex-<version>/plugins/         Qt platform plugins
      apex-<version>/share/doc/Apex/  LICENSE, THIRD_PARTY.md, the IBM Plex Sans licence
  apex_<number>_amd64.deb             system Qt; Depends from dpkg-shlibdeps (needs dpkg-dev)
  apex-<number>-1.x86_64.rpm          system Qt; Requires generated by rpmbuild from the ELF (needs rpm)

The .deb and .rpm install to /usr with a desktop entry and the scalable icon. <number> is the
version without its -release suffix, which neither format allows.

On Windows it writes apex-<version>-windows-x64.zip: apex.exe, windeployqt output and, when run from
a Visual Studio environment, the C++ runtime DLLs app-local, so the zip runs without the VC++
redistributable. --installer turns that zip into apex-<version>-windows-x64.exe with NSIS's makensis
(Linux or Windows): a per-machine install under Program Files with a Start menu shortcut and an
uninstaller that removes only the files it installed.

An AppImage is not produced: it needs appimagetool plus a patched Qt, which is not trivial
(plan 0.1.10 allows skipping it). The Vulkan loader and GPU drivers always come from the system.
The version comes from version.txt plus the build number (0 for ad-hoc packages).
"""
import argparse
import hashlib
import os
import platform
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SUMMARY = "Level editor for Source-engine maps (Strata Source, Portal 2: Community Edition)"
DESCRIPTION = """Apex is a native level editor for Source-engine maps, built for the Strata Source
toolchain. It reads and writes .vmf files, edits them in Vulkan viewports, compiles them with
the real Source tools, launches the game and previews lighting in the editor."""
HOMEPAGE = "https://github.com/Console796/apex"
MAINTAINER = "Geoffrey Taylor <geoffreyroberttaylor@gmail.com>"

# Libraries that must come from the host, not the bundle.
SYSTEM_LIB = re.compile(
    r"^(linux-vdso|ld-linux|libc\.|libm\.|libdl|libpthread|librt|libutil|libresolv|libgcc_s|"
    r"libstdc\+\+|libvulkan|libGL|libEGL|libGLX|libOpenGL|libX|libxcb|libxkbcommon|libwayland|"
    r"libdrm|libgbm|libfontconfig|libfreetype|libharfbuzz|libdbus|libglib|libgobject|libgio|"
    r"libgmodule|libsystemd|libz\.|libasound|libpulse|"
    # Host codecs are never bundled: the distro FFmpeg configuration is GPL (0.4.1 D4).
    # ldd also lists libmp3lame transitively through the host PulseAudio library.
    r"libavcodec|libavformat|libavutil|libavfilter|libavdevice|libswscale|libswresample|"
    r"libpostproc|libx264|libx265|libmp3lame)")

LAUNCHER = """#!/bin/sh
here="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
export LD_LIBRARY_PATH="$here/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export QT_PLUGIN_PATH="$here/plugins${QT_PLUGIN_PATH:+:$QT_PLUGIN_PATH}"
exec "$here/bin/apex" "$@"
"""

DESKTOP = f"""[Desktop Entry]
Type=Application
Name=Apex
GenericName=Level Editor
Comment={SUMMARY}
Exec=apex %f
Icon=apex
Terminal=false
Categories=Development;Graphics;3DGraphics;
"""


def run(cmd, **kw):
    print("+", " ".join(map(str, cmd)))
    subprocess.run(cmd, check=True, **kw)


def version(build_dir: Path) -> str:
    base = (ROOT / "version.txt").read_text().split()[0]
    base, sep, suffix = base.partition("-")  # "0.2.11-release" -> suffix "release"
    n = "0"
    cache = build_dir / "CMakeCache.txt"
    if cache.exists():
        m = re.search(r"^APEX_BUILD_NUMBER:\w+=(\d+)", cache.read_text(), re.M)
        if m:
            n = m.group(1)
    parts = base.split(".")
    while len(parts) < 3:
        parts.append("0")
    return ".".join(parts[:3] + [n]) + (f"-{suffix}" if sep else "")


def qt_prefix_from_cache(build_dir: Path):
    cache = build_dir / "CMakeCache.txt"
    if cache.exists():
        m = re.search(r"^Qt6_DIR:\w+=(.+)$", cache.read_text(), re.M)
        if m:
            return Path(m.group(1)).resolve().parents[2]  # <prefix>/lib/cmake/Qt6 -> <prefix>
    return None


def install(build_dir: Path, prefix: Path):
    run(["cmake", "--install", str(build_dir), "--prefix", str(prefix), "--strip"])


def bundle_qt_linux(stage: Path, exe: Path, qt_prefix):
    lib = stage / "lib"
    lib.mkdir(exist_ok=True)
    seen = set()

    def deps(path):
        out = subprocess.run(["ldd", str(path)], capture_output=True, text=True, check=True).stdout
        for line in out.splitlines():
            m = re.match(r"\s*(\S+) => (/\S+)", line)
            if m:
                yield m.group(1), Path(m.group(2))

    todo = [exe]
    plugdir = None
    for _, p in deps(exe):
        if p.name.startswith("libQt6Core"):
            plugdir = p.resolve().parent / "qt6" / "plugins"
            if not plugdir.exists() and qt_prefix:
                plugdir = qt_prefix / "plugins"
    plugins = stage / "plugins"
    if plugdir and plugdir.exists():
        # Intentionally omit multimedia: the host FFmpeg plugin pulls a GPL-configured
        # FFmpeg (0.4.1 confirmation, 0.1 D4). Linux ships without playback.
        for sub in ("platforms", "iconengines", "imageformats", "wayland-decoration-client",
                    "wayland-graphics-integration-client", "wayland-shell-integration",
                    "xcbglintegrations"):
            if (plugdir / sub).is_dir():
                shutil.copytree(plugdir / sub, plugins / sub, symlinks=False, dirs_exist_ok=True)
        todo += list(plugins.rglob("*.so"))
    else:
        print("warning: Qt plugin directory not found; platform plugins not bundled")
    while todo:
        f = todo.pop()
        for name, path in deps(f):
            if name in seen or SYSTEM_LIB.match(name):
                continue
            seen.add(name)
            shutil.copy2(path.resolve(), lib / name)
            todo.append(path)


def package_txz(build_dir, out, work, bundle, qt_prefix, ver):
    top = f"apex-{ver}"
    stage = work / "txz" / top
    install(build_dir, stage)
    exe = stage / "bin" / "apex"
    if bundle:
        bundle_qt_linux(stage, exe, qt_prefix)
        (stage / "apex").write_text(LAUNCHER)
        (stage / "apex").chmod(0o755)
    archive = out / f"{top}-linux-{platform.machine()}.tar.xz"
    with tarfile.open(archive, "w:xz", preset=9) as tf:
        tf.add(stage, arcname=top)
    return archive


def stage_usr(build_dir, root: Path):
    """cmake --install to <root>/usr plus the desktop entry and icon the system packages carry."""
    usr = root / "usr"
    install(build_dir, usr)
    apps = usr / "share" / "applications"
    apps.mkdir(parents=True, exist_ok=True)
    (apps / "apex.desktop").write_text(DESKTOP)
    icons = usr / "share" / "icons" / "hicolor" / "scalable" / "apps"
    icons.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / "src" / "ui" / "icons" / "apex.svg", icons / "apex.svg")
    for p in [root, *root.rglob("*")]:
        p.chmod(0o755 if p.is_dir() or os.access(p, os.X_OK) else 0o644)
    return usr


def package_deb(build_dir, out, work, number):
    if not shutil.which("dpkg-shlibdeps"):
        sys.exit("deb: dpkg-shlibdeps not found (install dpkg-dev)")
    root = work / "deb"
    usr = stage_usr(build_dir, root)
    # dpkg-shlibdeps reads debian/control from its working directory.
    ctl = work / "deb-shlibdeps"
    (ctl / "debian").mkdir(parents=True)
    (ctl / "debian" / "control").write_text("Source: apex\n\nPackage: apex\nArchitecture: any\n")
    out_text = subprocess.run(["dpkg-shlibdeps", "-O", "-e", str(usr / "bin" / "apex")], cwd=ctl,
                              check=True, capture_output=True, text=True).stdout
    depends = re.search(r"^shlibs:Depends=(.*)$", out_text, re.M).group(1)
    size_kb = sum(f.stat().st_size for f in root.rglob("*") if f.is_file()) // 1024
    debian = root / "DEBIAN"
    debian.mkdir()
    with open(debian / "md5sums", "w") as f:
        for p in sorted(usr.rglob("*")):
            if p.is_file():
                f.write(f"{hashlib.md5(p.read_bytes()).hexdigest()}  {p.relative_to(root)}\n")
    description = SUMMARY + "\n" + "\n".join(" " + line for line in DESCRIPTION.splitlines())
    (debian / "control").write_text(
        f"Package: apex\nVersion: {number}\nArchitecture: amd64\nMaintainer: {MAINTAINER}\n"
        f"Installed-Size: {size_kb}\nDepends: {depends}\n"
        # The Wayland platform plugin and the SVG icon engine are separate packages on Debian.
        "Recommends: qt6-wayland, qt6-svg-plugins\n"
        f"Section: devel\nPriority: optional\nHomepage: {HOMEPAGE}\nDescription: {description}\n")
    archive = out / f"apex_{number}_amd64.deb"
    run(["dpkg-deb", "--root-owner-group", "-Zxz", "--build", str(root), str(archive)])
    return archive


def package_rpm(build_dir, out, work, number):
    if not shutil.which("rpmbuild"):
        sys.exit("rpm: rpmbuild not found (install rpm)")
    stage = work / "rpm-stage"
    usr = stage_usr(build_dir, stage)
    files = sorted("/" + str(p.relative_to(stage)) for p in usr.rglob("*") if p.is_file())
    top = work / "rpmbuild"
    spec = top / "apex.spec"
    top.mkdir()
    # The binaries are already built and stripped: no debuginfo split, no build-id links.
    spec.write_text(
        f"Name: apex\nVersion: {number}\nRelease: 1\nSummary: {SUMMARY}\nLicense: MIT AND OFL-1.1\n"
        f"URL: {HOMEPAGE}\n"
        "%global debug_package %{nil}\n%global _build_id_links none\n%global __strip /bin/true\n"
        f"%description\n{DESCRIPTION}\n"
        f"%install\ncp -a {stage}/. %{{buildroot}}/\n"
        "%files\n" + "\n".join(files) + "\n")
    run(["rpmbuild", "-bb", "--target", "x86_64", "--define", f"_topdir {top}",
         "--define", f"_rpmdir {top / 'RPMS'}", str(spec)])
    built = next((top / "RPMS").rglob("*.rpm"))
    archive = out / built.name
    shutil.copy2(built, archive)
    return archive


def package_windows(build_dir, out, work, bundle, qt_prefix, ver):
    top = f"apex-{ver}"
    stage = work / top
    install(build_dir, stage)
    if bundle:
        tool = (qt_prefix / "bin" / "windeployqt.exe") if qt_prefix else None
        exe = str(tool) if tool and tool.exists() else shutil.which("windeployqt")
        if not exe:
            sys.exit("windeployqt not found; pass --qt-prefix or --no-bundle-qt")
        # Include Qt6Svg.dll and both SVG loaders even though icons render through QSvgRenderer.
        run([exe, "--svg", "--include-plugins", "qsvg,qsvgicon", "--no-translations", "--no-system-d3d-compiler", str(stage / "apex.exe")])
    # App-local C++ runtime, so the zip runs on a machine without the VC++ redistributable.
    redist = os.environ.get("VCToolsRedistDir")
    crt = sorted(Path(redist, "x64").glob("Microsoft.VC*.CRT")) if redist else []
    if crt:
        for dll in crt[-1].glob("*.dll"):
            shutil.copy2(dll, stage / dll.name)
    else:
        print("warning: VCToolsRedistDir not set; the zip needs the VC++ redistributable installed")
    archive = out / f"{top}-windows-x64.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(stage.rglob("*")):
            if f.is_file():
                zf.write(f, f.relative_to(work))
    return archive


def nsis_path(p: Path) -> str:
    return str(p).replace("/", "\\")


def package_installer(zip_path: Path, out, work):
    """NSIS installer from a Windows zip, so it can be built on Linux from the zip CI copies back."""
    makensis = shutil.which("makensis")
    if not makensis:
        sys.exit("installer: makensis not found (install nsis)")
    m = re.match(r"apex-(.+)-windows-x64\.zip$", zip_path.name)
    if not m:
        sys.exit(f"installer: {zip_path.name} is not an apex-<version>-windows-x64.zip")
    ver = m.group(1)
    with zipfile.ZipFile(zip_path) as zf:
        zf.extractall(work)
    stage = work / f"apex-{ver}"
    files = sorted(p.relative_to(stage) for p in stage.rglob("*") if p.is_file())
    dirs = sorted({d for f in files for d in f.parents if str(d) != "."}, key=lambda d: -len(d.parts))
    size_kb = sum((stage / f).stat().st_size for f in files) // 1024
    key = r"Software\Microsoft\Windows\CurrentVersion\Uninstall\Apex"
    lic = next((stage / n for n in ("LICENSE", "LICENSE.txt") if (stage / n).exists()), None)
    installs = []
    for d in sorted({f.parent for f in files}, key=lambda d: d.parts):
        installs.append(f'  SetOutPath "$INSTDIR\\{nsis_path(d)}"' if str(d) != "." else '  SetOutPath "$INSTDIR"')
        for f in files:
            if f.parent == d:
                installs.append(f'  File "{nsis_path(stage / f)}"')
    removes = [f'  Delete "$INSTDIR\\{nsis_path(f)}"' for f in files]
    removes += [f'  RMDir "$INSTDIR\\{nsis_path(d)}"' for d in dirs]
    exe = out / f"apex-{ver}-windows-x64.exe"
    script = work / "apex.nsi"
    script.write_text("\n".join([
        "Unicode true",
        "SetCompressor /SOLID lzma",
        '!include "MUI2.nsh"',
        '!include "x64.nsh"',
        f'Name "Apex {ver}"',
        f'OutFile "{nsis_path(exe.resolve())}"',
        'InstallDir "$PROGRAMFILES64\\Apex"',
        f'InstallDirRegKey HKLM "{key}" "InstallLocation"',
        "RequestExecutionLevel admin",
        f'VIProductVersion "{re.match(r"[0-9.]+", ver).group(0)}"',
        'VIAddVersionKey "ProductName" "Apex"',
        f'VIAddVersionKey "ProductVersion" "{ver}"',
        f'VIAddVersionKey "FileVersion" "{ver}"',
        'VIAddVersionKey "FileDescription" "Apex installer"',
        'VIAddVersionKey "LegalCopyright" "MIT License"',
        '!define MUI_ICON "${NSISDIR}\\Contrib\\Graphics\\Icons\\modern-install.ico"',
        '!define MUI_UNICON "${NSISDIR}\\Contrib\\Graphics\\Icons\\modern-uninstall.ico"',
        '!define MUI_FINISHPAGE_RUN "$INSTDIR\\apex.exe"',
        "!insertmacro MUI_PAGE_WELCOME",
        *([f'!insertmacro MUI_PAGE_LICENSE "{nsis_path(lic)}"'] if lic else []),
        "!insertmacro MUI_PAGE_DIRECTORY",
        "!insertmacro MUI_PAGE_INSTFILES",
        "!insertmacro MUI_PAGE_FINISH",
        "!insertmacro MUI_UNPAGE_CONFIRM",
        "!insertmacro MUI_UNPAGE_INSTFILES",
        '!insertmacro MUI_LANGUAGE "English"',
        "Function .onInit",
        "  ${IfNot} ${RunningX64}",
        '    MessageBox MB_ICONSTOP "Apex needs 64-bit Windows."',
        "    Abort",
        "  ${EndIf}",
        "  SetRegView 64",
        "FunctionEnd",
        "Function un.onInit",
        "  SetRegView 64",
        "FunctionEnd",
        'Section "Apex"',
        "  SetShellVarContext all",
        *installs,
        '  SetOutPath "$INSTDIR"',
        '  WriteUninstaller "$INSTDIR\\uninstall.exe"',
        '  CreateShortCut "$SMPROGRAMS\\Apex.lnk" "$INSTDIR\\apex.exe"',
        f'  WriteRegStr HKLM "{key}" "DisplayName" "Apex"',
        f'  WriteRegStr HKLM "{key}" "DisplayVersion" "{ver}"',
        f'  WriteRegStr HKLM "{key}" "Publisher" "Apex contributors"',
        f'  WriteRegStr HKLM "{key}" "URLInfoAbout" "{HOMEPAGE}"',
        f'  WriteRegStr HKLM "{key}" "DisplayIcon" "$INSTDIR\\apex.exe"',
        f'  WriteRegStr HKLM "{key}" "InstallLocation" "$INSTDIR"',
        f'  WriteRegStr HKLM "{key}" "UninstallString" \'"$INSTDIR\\uninstall.exe"\'',
        f'  WriteRegDWORD HKLM "{key}" "NoModify" 1',
        f'  WriteRegDWORD HKLM "{key}" "NoRepair" 1',
        f'  WriteRegDWORD HKLM "{key}" "EstimatedSize" {size_kb}',
        "SectionEnd",
        "Section Uninstall",
        "  SetShellVarContext all",
        '  Delete "$SMPROGRAMS\\Apex.lnk"',
        # Only what the installer put there: a directory the user chose keeps anything else in it.
        *removes,
        '  Delete "$INSTDIR\\uninstall.exe"',
        '  RMDir "$INSTDIR"',
        f'  DeleteRegKey HKLM "{key}"',
        "SectionEnd",
        "",
    ]))
    run([makensis, "-V2", "-NOCD", str(script)])
    return exe


def main():
    win = os.name == "nt"
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--build-dir", type=Path,
                    default=ROOT / "build" / ("windows-msvc-release" if win else "linux-gcc-release"))
    ap.add_argument("--out", type=Path, default=ROOT / "dist")
    ap.add_argument("--formats", default="txz,deb,rpm", help="Linux: comma-separated txz, deb, rpm")
    ap.add_argument("--installer", type=Path, metavar="ZIP", help="build the NSIS installer from a Windows zip")
    ap.add_argument("--qt-prefix", type=Path, default=None)
    ap.add_argument("--no-bundle-qt", action="store_true", help="skip Qt runtime bundling")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="apex-package-") as tmp:
        work = Path(tmp)
        if a.installer:
            print("wrote", package_installer(a.installer.resolve(), a.out, work))
            return
        if not (a.build_dir / "CMakeCache.txt").exists():
            sys.exit(f"{a.build_dir} is not a configured build tree (build the `apex` target first)")
        qt = a.qt_prefix or qt_prefix_from_cache(a.build_dir)
        ver = version(a.build_dir)
        if win:
            print("wrote", package_windows(a.build_dir, a.out, work, not a.no_bundle_qt, qt, ver))
            return
        number = ver.split("-")[0]
        formats = [f.strip() for f in a.formats.split(",") if f.strip()]
        unknown = set(formats) - {"txz", "deb", "rpm"}
        if unknown:
            sys.exit(f"unknown --formats: {', '.join(sorted(unknown))}")
        for f in formats:
            path = (package_txz(a.build_dir, a.out, work, not a.no_bundle_qt, qt, ver) if f == "txz" else
                    package_deb(a.build_dir, a.out, work, number) if f == "deb" else
                    package_rpm(a.build_dir, a.out, work, number))
            print("wrote", path)


if __name__ == "__main__":
    main()
