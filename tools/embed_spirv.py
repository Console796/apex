#!/usr/bin/env python3
"""Embed SPIR-V binaries as constexpr uint32_t arrays in a C++ header (plan 0.1, D14).

Usage: embed_spirv.py <out.hpp> <id>=<in.spv> [<id>=<in.spv> ...]

Each id becomes `inline constexpr std::uint32_t <id>[]` in namespace apex::render::shaders. The
header is written in full on every run, so it is only rebuilt when CMake reruns this script.
"""
import struct
import sys
from pathlib import Path

SPIRV_MAGIC = 0x07230203


def main(argv):
    if len(argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    out = Path(argv[1])
    lines = [
        "// Generated by tools/embed_spirv.py from src/render/shaders. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace apex::render::shaders {",
        "",
    ]
    for arg in argv[2:]:
        ident, _, path = arg.partition("=")
        data = Path(path).read_bytes()
        if len(data) % 4 != 0 or len(data) < 20:
            print(f"{path}: not a SPIR-V module", file=sys.stderr)
            return 1
        words = struct.unpack(f"<{len(data) // 4}I", data)
        if words[0] != SPIRV_MAGIC:
            print(f"{path}: bad SPIR-V magic", file=sys.stderr)
            return 1
        lines.append(f"// {Path(path).name}: {len(words)} words")
        lines.append(f"inline constexpr std::uint32_t {ident}[] = {{")
        for i in range(0, len(words), 8):
            chunk = ", ".join(f"0x{w:08x}u" for w in words[i:i + 8])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
    lines.append("} // namespace apex::render::shaders")
    lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
